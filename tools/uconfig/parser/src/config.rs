macro_rules! continue_set_false {
    ($ident:ident) => {
        $ident = false;
        continue
    };
}

pub fn import(namespace: &mut Namespace, config: &str) {
    let mut last_token_was_key = false;
    let mut last_key = String::default();

    for token in ConfigToken::lexer(config) {
        match token {
            Ok(ConfigToken::Identifier(key)) => {
                last_key = key;
                last_token_was_key = true;
            }
            Ok(ConfigToken::Boolean(_)) | Ok(ConfigToken::Number(_)) | Ok(ConfigToken::QuotedString(_)) => {
                if !last_token_was_key {
                    continue_set_false!(last_token_was_key);
                }

                // convert token -> value
                let value = match token {
                    Ok(ConfigToken::Boolean(boolean)) => Value::Bool(boolean),
                    Ok(ConfigToken::Number(int)) => Value::Int(int),
                    Ok(ConfigToken::QuotedString(string)) => Value::String(string),
                    _ => unreachable!(),
                };

                // check if the key is within the namespace
                let Some(&idx) = namespace.hashmap.get(&last_key) else {
                    continue_set_false!(last_token_was_key);
                };

                // set the current value to the one found in the config while checking the type
                let option = &mut namespace.vector[idx];
                match &mut option.current {
                    Value::Selection(selection) => {
                        let basic = value.to_basic();
                        let Some(selected) = selection.values.iter().position(|value| value == &basic) else {
                            continue_set_false!(last_token_was_key);
                        };

                        selection.selected = selected;
                    },
                    _ => {
                        if std::mem::discriminant(&option.current) != std::mem::discriminant(&value) {
                            continue_set_false!(last_token_was_key);
                        }
                        option.current = value
                    }
                }


                last_token_was_key = false;
            }
            Ok(ConfigToken::Equals) => {
                if !last_token_was_key {
                    continue_set_false!(last_token_was_key);
                }
            }
            _ => { continue_set_false!(last_token_was_key); },
        }
    }
}

struct VisibleIter<'a> {
    namespace: &'a Namespace,
    parent: Vec<usize>,
    visible: Vec<bool>,
    index: usize,
}

impl<'a> Iterator for VisibleIter<'a> {
    type Item = &'a ConfigOption;

    fn next(&mut self) -> Option<Self::Item> {
        while let Some(option) = self.namespace.vector.get(self.index) {
            let i = self.index;
            self.index += 1;

            for &child in &option.children {
                self.parent[child] = i;
            }

            let passes = option.valid(self.namespace) == ExpressionResult::Passed;

            self.visible[i] = passes && (i == 0 || self.visible[self.parent[i]]);

            if self.visible[i] && !option.is_env && i != 0 {
                return Some(option);
            }
        }
        None
    }
}

impl Namespace {
    fn visible(&self) -> VisibleIter<'_> {
        VisibleIter {
            namespace: self,
            parent: vec![0; self.vector.len()],
            visible: vec![false; self.vector.len()],
            index: 0,
        }
    }
}

fn escape_c(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out
}

pub fn export_c_header(namespace: &Namespace) -> String {
    let mut output = String::from(
        "// This file was autogenerated by uconfig, please do not edit\n".to_owned() +
        "// it manually! Use `make menuconfig` instead." +
        "#pragma once\n\n"
    );
    for option in namespace.visible() {
        let line = match option.current.to_basic() {
            BasicValue::Bool(true) => format!("#define {}\n", option.name),
            BasicValue::Bool(false) => format!("// #define {}\n", option.name),
            BasicValue::Int(value) => format!("#define {} {value}ull\n", option.name),
            BasicValue::String(value) => format!("#define {} \"{}\"\n", option.name, escape_c(&value)),
        };
        output.push_str(&line);
    }
    output
}
